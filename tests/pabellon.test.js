"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {JSDOM}=require("jsdom");
const root=path.join(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
const dom=new JSDOM(read("pabellon.html"),{url:"https://example.test/pabellon.html",runScripts:"outside-only",pretendToBeVisual:true});
const w=dom.window,doc=w.document;
let callback,listener;
w.requestAnimationFrame=fn=>{callback=fn;};
w.BroadcastChannel=class {set onmessage(fn){listener=fn;} postMessage(){}};
const sample=JSON.parse(read("datos-almanzor-2026.json"));
for(const [category,div] of Object.entries(sample.categories)){
  const slots=category==="Femenino"?["F1","F2","F3","F4","F5"]:
    ["A1","A2","A3","A4","A5","B1","B2","B3","B4","C1","C2","C3","C4"].map(s=>(category==="Mixto"?"X":"M")+s);
  div.pairs=slots.map((id,i)=>({id,p1:"Jugador "+i,p2:"Pareja "+i}));
  div.groups=Object.fromEntries(slots.map(s=>[s,s]));div.results={};div.confirmed={};
}
w.fetch=async()=>({ok:true,json:async()=>sample});
const fixtures=["torneo.js","calendario-almanzor.js","almanzor.js","pabellon-comun.js","pabellon.js"];
w.eval(fixtures.map(read).join("\n"));
(async()=>{
  await new Promise(r=>setImmediate(r));
  const settings={category:"Mixto",order:["clas","horario","cuadro","resultados"],auto:true,paused:false,seconds:10};
  const cmd=extra=>listener({data:{type:"setup",setup:settings,...extra}});
  const heading=()=>doc.querySelector("h1").textContent;
  const frame=doc.querySelector("main");
  let h=300,now=0;
  Object.defineProperties(frame,{clientHeight:{get:()=>300},scrollHeight:{get:()=>h}});
  const advance=ms=>{for(let i=0;i<ms;i+=50){now+=50;callback(now);}};
  cmd({});assert.equal(heading(),"Clasificación");
  for(const [category,sizes] of [["Mixto",[5,4,4]],["Masculino",[5,4,4]],["Femenino",[5]]]){
    settings.category=category;cmd({});
    const tables=Array.from(frame.querySelectorAll("table"));
    assert.deepEqual(tables.map(t=>t.tBodies[0].rows.length),sizes);
    assert.deepEqual(tables.map(t=>t.tHead.rows[0].textContent),sizes.length===1?["Grupo único"]:["Grupo A","Grupo B","Grupo C"]);
    for(const table of tables)assert.equal(table.tBodies[0].rows[0].cells[0].textContent,"1");
  }
  settings.category="Mixto";cmd({});advance(10050);assert.equal(heading(),"Próximos partidos");
  h=1000;advance(2900);assert.equal(frame.scrollTop,0);
  advance(8000);assert.ok(frame.scrollTop>0 && frame.scrollTop<700);
  settings.paused=true;cmd({});const stopped=frame.scrollTop;
  advance(20000);assert.equal(frame.scrollTop,stopped);assert.equal(heading(),"Próximos partidos");
  settings.paused=false;cmd({});advance(12500);assert.equal(frame.scrollTop,700);
  assert.equal(heading(),"Próximos partidos");advance(3200);assert.match(heading(),/Cuadro eliminatorio · Previa/);
  settings.auto=false;cmd({page:"resultados"});h=300;advance(30000);assert.equal(heading(),"Últimos resultados");
  settings.category="Femenino";cmd({page:"cuadro/Semifinal"});assert.equal(doc.querySelector("#mode").textContent,"Femenino");
  assert.equal(frame.querySelectorAll("tbody tr").length,2);cmd({step:1});assert.equal(heading(),"Cuadro eliminatorio · Final");
  cmd({step:-1});assert.equal(heading(),"Cuadro eliminatorio · Semifinal");
  const desk=new JSDOM(read("admin.html"),{url:"https://example.test/admin.html",runScripts:"outside-only"});
  const d=desk.window;
  d.BroadcastChannel=class {postMessage(data){listener({data:JSON.parse(JSON.stringify(data))});}};
  d.eval([...fixtures.slice(0,-1),"pabellon-mesa.js"].map(read).join("\n"));
  const control=id=>d.document.getElementById("screen-"+id);
  const change=(input,value)=>{input.value=value;input.dispatchEvent(new d.Event("change"));};
  change(control("category"),"Masculino");
  change(control("seconds"),"20");
  control("order").querySelector('[data-up="horario"]').click();
  control("order").querySelector('[data-view="cuadro"]').click();
  change(control("view"),"horario");control("pin").click();
  assert.equal(heading(),"Próximos partidos");assert.equal(doc.querySelector("#mode").textContent,"Masculino");
  const stored=JSON.parse(d.localStorage.getItem(d.localStorage.key(0)));
  assert.deepEqual(stored.order,["horario","clas","resultados"]);assert.equal(stored.seconds,20);
  assert.equal(stored.auto,false);assert.equal(stored.fixed,"horario");
  control("next").click();assert.equal(heading(),"Clasificación");
  const result=JSON.parse(JSON.stringify(sample));
  result.meta.updatedAt="2099-01-01T00:00:00.000Z";
  const division=result.categories.Masculino;
  division.results.MG01={aId:division.groups.MA2,bId:division.groups.MA5,sets:[{s1:"21",s2:"10"}]};
  d.dispatchEvent(new d.CustomEvent("torneo-publicado",{detail:result}));
  change(control("view"),"resultados");control("pin").click();
  assert.match(frame.textContent,/21–10/);
  desk.window.close();
  dom.window.close();console.log("OK · proyección, pausa, recorrido completo, tiempos de lectura, fijación y rondas");
})().catch(e=>{console.error(e);dom.window.close();process.exitCode=1;});
